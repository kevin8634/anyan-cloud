gen D2_bellmother "$DLC" "钟楼最顶层，一口比教堂还大的母钟悬在断裂的穹顶下，钟体布满熔痕，周围铁链垂向深渊，下方是翻涌的黑色潮水，钟缘透出暗红熔光。"
