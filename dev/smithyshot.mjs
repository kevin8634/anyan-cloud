// v1.2.40 铸造台浏览器实测：比赛版 DLC 写实战士，装主手 → 武器库换外观 → 离线退回 → 在线生成（fetch 桩，返回 GLB）→ 截图
// 用法：node dev/smithyshot.mjs [html] [输出目录]
import { chromium } from 'playwright-core';
import { resolve } from 'path';
import { readFileSync, mkdirSync } from 'fs';
const HTML = resolve(process.argv[2] || 'web/index_dlc1_比赛版.html'), OUT = process.argv[3] || '/tmp/smithy'; mkdirSync(OUT, { recursive: true });
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
let fail = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fail++; };
const page = await b.newPage({ viewport: { width: 1280, height: 720 } });
const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.text().startsWith('equip')) console.log(m.text()); });
await page.goto('file://' + HTML);
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('darkrock_settings', JSON.stringify({ quality: 'high', charModel: 'new' })); });
await page.reload();
await page.waitForFunction(() => window.__game && document.getElementById('start').textContent === '开始冒险', null, { timeout: 120000 });
await page.evaluate(() => window.__game.startGame('warrior'));
await page.waitForTimeout(3000);
await page.evaluate(() => { const g = window.__game; g.tutFinish?.();  });
await page.waitForTimeout(1000);
const S = 'window.__dlc1.smithy';
const lib = await page.evaluate(`${S}.lib()`);
ok(lib.length >= 8, `武器库 ${lib.length} 把：${lib.map(l => l.key).join(', ')}`);
const pick = await page.evaluate(`${S}.pick('缠着海藻的锈蚀锚形巨斧', 'sword')`);
ok(/axe/.test(pick ?? ''), `关键词 → ${pick}`);
const fam = await page.evaluate(`${S}.pick('一个发光的药瓶', 'sword')`);
ok(!/flask|chakram|staff|wand|great/.test(fam ?? ''), `握法分组：剑只能换单手近战外观 → ${fam}`);
const r0 = await page.evaluate(`${S}.run('沉在海底的钟铜长剑')`);
ok(r0.ok && !r0.online, `离线：${r0.msg} → ${r0.key}`);
const lux = await page.evaluate(() => { let n = 0; window.__game.player.rig.root.traverse(o => { if (o.name?.startsWith('lux_weapon') || o.name?.startsWith('lux_forge')) n++; }); return n; });
ok(lux >= 1, `角色手上有 Lux 武器网格 ${lux}`);
await page.screenshot({ path: `${OUT}/offline.png` });
const b64 = readFileSync('assets_aholo/props/weapon_rock_greataxe.glb').toString('base64');
await page.evaluate(() => localStorage.setItem('darkrock_forge_api', 'https://forge.test'));
const r1 = await page.evaluate(async b64 => window.__dlc1.smithy.run('缠着海藻的锈蚀锚形巨斧', async () => ({ ok: true, status: 200, json: async () => ({ glb: b64 }) })), b64);
ok(r1.ok && r1.online && /^forge_/.test(r1.key), `在线（桩）：${r1.msg} → ${r1.key}`);
const has = await page.evaluate(k => { let f = false; window.__game.player.rig.root.traverse(o => { if (o.name === 'lux_' + k) f = true; }); return f; }, r1.key);
ok(has, '换上了生成的武器');
await page.evaluate(() => window.__dlc1.smithy.open());
await page.waitForTimeout(400);
await page.screenshot({ path: `${OUT}/panel.png` });
ok(errors.length === 0, `页面错误 ${errors.length}${errors.length ? '：' + errors.slice(0, 3).join(' | ') : ''}`);
await b.close(); console.log(fail ? `FAILED ${fail}` : 'ALL PASS'); process.exit(fail ? 1 : 0);
