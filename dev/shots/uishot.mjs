import { chromium } from 'playwright-core';
const b = await chromium.launch({ args: ['--use-gl=swiftshader','--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1280, height: 760 } }); const errs = [];
p.on('pageerror', e => errs.push(e.message));
await p.addInitScript(() => { localStorage.clear(); });
await p.goto('file://'+process.cwd()+'/web/index.html');
await p.waitForFunction(() => window.__game && document.getElementById('start')?.textContent === '开始冒险', null, { timeout: 60000 });
await p.evaluate(() => { document.getElementById('class-pick').children[0].click(); document.getElementById('start').click(); });
await p.waitForTimeout(1500);
await p.evaluate(() => { const g = window.__game; g.progression.level = 30; g.ensureWild('redsand'); g.goMap('redsand'); });
await p.waitForTimeout(3000);
await p.screenshot({ path: '/tmp/ui_hud.png' });
await p.evaluate(() => window.__game.openWorldMap('world'));
await p.waitForTimeout(600); await p.screenshot({ path: '/tmp/ui_world.png' });
await p.evaluate(() => { const g = window.__game; g.togglePanel('worldmap', false); g.openRaidMap('ash_forge', true); });
await p.waitForTimeout(800); await p.screenshot({ path: '/tmp/ui_raidmap.png' });
await p.evaluate(() => { const g = window.__game; g.togglePanel('raidmap', false); g.openDropGuide(); });
await p.waitForTimeout(800); await p.screenshot({ path: '/tmp/ui_guide.png' });
console.log('errors', errs.slice(0,3));
await b.close();
