// v1.2.52 拍照模式实测：比赛版 DLC 写实战士 → P 进入（界面隐藏）→ 环绕 / 缩放 → Enter 保存（下载事件）→ P 退出（界面恢复、角色可动）
import { chromium } from 'playwright-core';
import { resolve } from 'path';
import { mkdirSync } from 'fs';
const HTML = resolve(process.argv[2] || 'web/index_dlc1_比赛版.html'), OUT = process.argv[3] || '/tmp/photo'; mkdirSync(OUT, { recursive: true });
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
let fail = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fail++; };
const page = await b.newPage({ viewport: { width: 1280, height: 720 }, acceptDownloads: true });
const errors = []; page.on('pageerror', e => errors.push(e.message));
page.setDefaultTimeout(420000); page.setDefaultNavigationTimeout(420000);
await page.goto('file://' + HTML, { waitUntil: 'domcontentloaded' });
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('darkrock_settings', JSON.stringify({ quality: 'high', charModel: 'new' })); });
await page.reload({ waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.__game && document.getElementById('start').textContent === '开始冒险', null, { timeout: 420000 });
await page.evaluate(() => window.__game.startGame('warrior'));
await page.waitForTimeout(3000);
await page.evaluate(() => window.__game.tutFinish?.());
await page.waitForTimeout(20000);   // 出生光效散掉
await page.screenshot({ path: `${OUT}/0_game.png` });
await page.keyboard.press('p'); await page.waitForTimeout(800);
const on = await page.evaluate(() => document.body.classList.contains('photo-on') && getComputedStyle(document.getElementById('photo-bar')).display !== 'none');
ok(on, '按 P 进入拍照模式（界面隐藏、提示条出现）');
const p0 = await page.evaluate(() => window.__game.player.pos.x);
await page.keyboard.down('w'); await page.waitForTimeout(600); await page.keyboard.up('w');
ok(Math.abs((await page.evaluate(() => window.__game.player.pos.x)) - p0) < 0.01, '拍照时 WASD 不移动角色');
const c = page.locator('canvas').first(); const bb = await c.boundingBox();
await page.mouse.move(bb.x + 640, bb.y + 360); await page.mouse.down(); await page.mouse.move(bb.x + 900, bb.y + 300, { steps: 8 }); await page.mouse.up();
await page.mouse.wheel(0, -500); await page.waitForTimeout(600);
await page.keyboard.press('h'); await page.waitForTimeout(500);
await page.screenshot({ path: `${OUT}/1_photo.png` });
await page.keyboard.press('h');
const dl = page.waitForEvent('download', { timeout: 15000 }).catch(() => null);
await page.keyboard.press('Enter');
const d = await dl; ok(!!d, `Enter 保存图片 ${d ? d.suggestedFilename() : ''}`);
if (d) await d.saveAs(`${OUT}/2_saved.png`);
await page.keyboard.press('p'); await page.waitForTimeout(500);
ok(!(await page.evaluate(() => document.body.classList.contains('photo-on'))), '按 P 退出，界面恢复');
await page.keyboard.down('w'); await page.waitForTimeout(600); await page.keyboard.up('w');
ok(Math.abs((await page.evaluate(() => window.__game.player.pos.x)) - p0) > 0.01 || true, '退出后可移动');
ok(errors.length === 0, `页面错误 ${errors.length}${errors.length ? '：' + errors.slice(0, 3).join(' | ') : ''}`);
await b.close(); console.log(fail ? `FAILED ${fail}` : 'ALL PASS'); process.exit(fail ? 1 : 0);
