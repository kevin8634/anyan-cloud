// v1.2.38c 录制模式自检：node dev/recshot.mjs <html> [输出目录]（?rec=1 打开，验证隐藏界面 / 自由相机 / 冻结 / 路径播放 / 1920×1080）
import { chromium } from 'playwright-core';
import { resolve } from 'path'; import { mkdirSync } from 'fs';
const [html, OUT = '/tmp/rec'] = process.argv.slice(2); mkdirSync(OUT, { recursive: true });
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await b.newPage({ viewport: { width: 960, height: 540 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
await page.goto('file://' + resolve(html) + '?rec=1');
await page.waitForFunction(() => window.__game && document.getElementById('start').textContent === '开始冒险', null, { timeout: 120000 });
await page.evaluate(() => { localStorage.setItem('darkrock_intro_seen', '1'); window.__game.startGame('warrior'); });
await page.waitForTimeout(3000);
await page.evaluate(() => window.__game.tutFinish?.());
const out = [];
const ok = (c, m) => { out.push((c ? '✓ ' : '✗ ') + m); if (!c) process.exitCode = 1; };
let s = await page.evaluate(() => { const cv = document.getElementById('game'); return { on: window.__game.recState().on, w: cv.width, h: cv.height, panel: !!document.getElementById('recpanel') }; });
ok(s.on && s.w === 1920 && s.h === 1080 && s.panel, `?rec=1 开启：画布 ${s.w}×${s.h}，面板 ${s.panel}`);
await page.screenshot({ path: `${OUT}/1_ui.png` });
await page.keyboard.press('Backslash'); await page.waitForTimeout(300);
s = await page.evaluate(() => ({ noUI: window.__game.recState().noUI, hud: getComputedStyle(document.getElementById('recpanel')).display, skill: [...document.body.children].filter(e => e.id !== 'game' && e.tagName !== 'SCRIPT' && e.tagName !== 'STYLE' && getComputedStyle(e).visibility !== 'hidden').map(e => e.id || e.tagName).slice(0, 5) }));
ok(s.noUI && s.hud === 'none' && s.skill.length === 0, `\\ 隐藏全部界面（剩余可见：${s.skill.join(',') || '无'}）`);
await page.screenshot({ path: `${OUT}/2_noui.png` });
await page.keyboard.press('Backquote');
const p0 = await page.evaluate(() => window.__game.recCam.position.toArray());
await page.keyboard.down('w'); await page.keyboard.down('e'); await page.waitForTimeout(3000); await page.keyboard.up('w'); await page.keyboard.up('e');
s = await page.evaluate(() => ({ free: window.__game.recState().free, pp: window.__game.player.pos.toArray() }));
const p1 = await page.evaluate(() => window.__game.recCam.position.toArray());
ok(s.free && p0 && p1 && Math.hypot(p1[0] - p0[0], p1[1] - p0[1], p1[2] - p0[2]) > 1, `\` 自由相机飞行：移动 ${p0 && p1 ? Math.hypot(p1[0] - p0[0], p1[1] - p0[1], p1[2] - p0[2]).toFixed(1) : '?'} 米`);
await page.keyboard.press('g'); await page.keyboard.press('z'); await page.keyboard.press('z');
s = await page.evaluate(() => window.__game.recState());
ok(s.freezeAI && s.timeScale === 0.5, `G 冻结怪物 ${s.freezeAI}，Z 时间 ×${s.timeScale}`);
await page.keyboard.press('Digit1'); await page.keyboard.down('a'); await page.waitForTimeout(800); await page.keyboard.up('a'); await page.keyboard.press('Digit2');
await page.keyboard.press('BracketLeft'); for (let i = 0; i < 6; i++) await page.keyboard.press('BracketLeft');
await page.keyboard.press('p'); await page.waitForTimeout(400);
s = await page.evaluate(() => window.__game.recState());
ok(s.playing, '1 / 2 记起终点，P 播放路径');
await page.waitForFunction(() => !window.__game.recState().playing, null, { timeout: 20000 }).catch(() => {});
s = await page.evaluate(() => window.__game.recState());
ok(!s.playing, '路径播放结束');
await page.screenshot({ path: `${OUT}/3_free.png` });
await page.keyboard.press('Backquote'); await page.keyboard.press('Backslash');
s = await page.evaluate(() => window.__game.recState());
ok(!s.free && !s.noUI, '退出自由相机 + 恢复界面');
console.log(out.join('\n')); console.log(errors.length ? 'ERRORS ' + errors.slice(0, 5).join(' | ') : 'NO ERRORS');
await b.close();
