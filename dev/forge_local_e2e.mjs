// 「启动铸造服务」端到端（无头 Chromium + 假 Aholo 服务端，不联网、不扣分）：
//   双击程序 → 托管评委版 html（同源，smithyMode = server）→ 铸造台填 Key（错 Key 红色、不发生成）→ 对 Key 绿色 → 铸造 → 自动取回 → 进「我的铸造品」并换上
// 用法：node dev/forge_local_e2e.mjs [html] [启动程序] [输出目录]
import { chromium } from 'playwright-core';
import { spawn } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';
const HTML = path.resolve(process.argv[2] || 'web/index_dlc1_比赛版.html');
const BIN = path.resolve(process.argv[3] || '/tmp/dist_local/启动铸造服务_linux_arm64');
const OUT = process.argv[4] || '/workspace/work/diag/uifix'; fs.mkdirSync(OUT, { recursive: true });
const FAKE = 18790, PORT = 18862;
let fail = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fail++; };
const EN_OK = t => !/[A-Za-z]/.test(String(t).replace(/Lux3D|Key|GLB|Aholo/g, ''));
const sleep = ms => new Promise(r => setTimeout(r, ms));
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'judgepkg-')), home = fs.mkdtempSync(path.join(os.tmpdir(), 'forgehome-'));
fs.symlinkSync(HTML, path.join(dir, '暗岩传说_深渊回响_评委版.html'));
if (fs.existsSync(path.join(path.dirname(HTML), 'music'))) fs.symlinkSync(path.join(path.dirname(HTML), 'music'), path.join(dir, 'music'));
const env = { ...process.env, NO_PROXY: '127.0.0.1,localhost', no_proxy: '127.0.0.1,localhost' };
const fake = spawn('node', ['dev/fake_aholo.mjs', String(FAKE)], { stdio: ['ignore', 'pipe', 'inherit'], env });
await new Promise(r => fake.stdout.on('data', d => /READY/.test(d) && r()));
let out = '';
const srv = spawn(BIN, [], { cwd: dir, env: { ...env, FORGE_HOME: home, AHOLO_API_BASE: `http://127.0.0.1:${FAKE}`, NO_BROWSER: '1', PORT: String(PORT), POLL_MS: '1000' }, stdio: ['ignore', 'pipe', 'pipe'] });
srv.stdout.on('data', d => { out += d; }); srv.stderr.on('data', d => { out += d; });
for (let k = 0; k < 100 && !/READY/.test(out); k++) await sleep(100);
ok(/READY/.test(out), `启动铸造服务（${path.basename(BIN)}）监听 127.0.0.1:${PORT}`);
const stats = async () => (await fetch(`http://127.0.0.1:${FAKE}/__stats`)).json();
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await b.newPage({ viewport: { width: 1280, height: 720 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
page.setDefaultTimeout(1500000);
const real = []; await page.route('https://api.aholo3d.cn/**', r => { real.push(r.request().url()); r.abort('failed'); });
await page.goto(`http://127.0.0.1:${PORT}/`, { waitUntil: 'domcontentloaded' });
await page.evaluate(() => { localStorage.setItem('darkrock_settings', JSON.stringify({ quality: 'high', charModel: 'new' })); localStorage.setItem('darkrock_intro_seen', '1'); });
await page.reload({ waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.__game && document.getElementById('start').textContent === '开始冒险', null, { timeout: 1500000, polling: 2000 });
console.log('title ready', new Date().toISOString());
await page.evaluate(() => document.getElementById('demo-enter').click());
await page.waitForTimeout(15000);
const rect = sel => page.evaluate(s => { const e = document.querySelector(s); if (!e) return null; e.scrollIntoView({ block: 'center' }); const r = e.getBoundingClientRect(); return { x: Math.round(r.left), y: Math.round(r.top), w: Math.round(r.width), h: Math.round(r.height) }; }, sel);
const click = async sel => { const r = await rect(sel); await page.mouse.click(r.x + Math.min(10, r.w / 2), r.y + Math.min(8, r.h / 2)); };
const msg = () => page.evaluate(() => { const e = document.querySelector('#d1-forge .msg'); return { t: e?.textContent ?? '', c: e?.className ?? '', col: e ? getComputedStyle(e).color : '' }; });
await page.evaluate(() => window.__dlc1.judge.act(0));
await page.waitForFunction(() => document.getElementById('fg-mode')?.textContent.includes('本机铸造服务'), null, { timeout: 60000, polling: 500 }).catch(() => {});
const m0 = await page.evaluate(() => ({ mode: window.__dlc1.smithy.mode(), label: document.getElementById('fg-mode')?.textContent, box: !!document.getElementById('fg-lkbox'), api: localStorage.getItem('darkrock_forge_api') }));
console.log('mode', JSON.stringify(m0));
ok(m0.mode === 'server' && m0.label.includes('本机铸造服务') && m0.box && m0.api === `http://127.0.0.1:${PORT}`, '同源打开 → server 模式，标签「本机铸造服务 · 在线生成」，有 Key 输入区');
await page.screenshot({ path: `${OUT}/20_local_service_mode.png` });
// 错 Key：红色、不生成
await click('#fg-lkey'); await page.keyboard.type('wrong-key-0000');
await click('#d1-forge [data-a="lkey"]');
await page.waitForFunction(() => !/正在/.test(document.querySelector('#d1-forge .msg')?.textContent ?? '正在'), null, { timeout: 120000, polling: 500 });
let m = await msg(); console.log('wrong key', JSON.stringify(m));
ok(m.c.includes('bad') && /Key 错误或已过期/.test(m.t) && EN_OK(m.t), `错 Key → 红色中文（${m.col}）`);
await page.screenshot({ path: `${OUT}/21_local_wrong_key_red.png` });
await page.evaluate(() => { window.__dlc1.smithy.show.speed = 3; document.getElementById('fg-p').value = '缠着海藻的锈蚀锚形长剑'; });
await click('#d1-forge [data-a="go"]');
await page.waitForFunction(() => /在线生成失败/.test(window.__dlc1.smithy.toast.text), null, { timeout: 300000, polling: 500 });
const t0 = await page.evaluate(() => window.__dlc1.smithy.toast.text); console.log('forge without key', t0);
let s = await stats();
ok(s.create === 0 && /没有发起生成/.test(t0) && EN_OK(t0), `没有有效 Key 时铸造 → 退回武器库、create ${s.create} 次（${t0}）`);
await page.waitForTimeout(4000);
// 对 Key：绿色
await page.evaluate(() => { if (!document.getElementById('d1-forge')) window.__dlc1.smithy.open(); });
await page.waitForTimeout(1500);
await page.evaluate(() => { const d = document.getElementById('fg-lkbox'); if (d) d.open = true; });
await click('#fg-lkey'); await page.keyboard.type('fake-good-key');
await click('#fg-lrem');
await click('#d1-forge [data-a="lkey"]');
await page.waitForFunction(() => /Key 正确/.test(document.querySelector('#d1-forge .msg')?.textContent ?? ''), null, { timeout: 120000, polling: 500 });
m = await msg(); console.log('good key', JSON.stringify(m));
ok(m.c.includes('ok') && EN_OK(m.t), `对 Key → 绿色（${m.col}）`);
ok(fs.existsSync(path.join(home, 'config.json')), '勾选「记在本机」→ 写入本机用户目录');
await page.screenshot({ path: `${OUT}/22_local_good_key_green.png` });
// 铸造 → 自动取回 → 我的铸造品
const n0 = await page.evaluate(() => window.__dlc1.smithy.items().length);
await page.evaluate(() => { document.getElementById('fg-p').value = '沉在海底的钟铜长剑'; });
await click('#d1-forge [data-a="go"]');
await page.waitForFunction(() => /铸造完成|在线生成失败/.test(window.__dlc1.smithy.toast.text), null, { timeout: 600000, polling: 1000 });
const t1 = await page.evaluate(() => window.__dlc1.smithy.toast.text); console.log('forge', t1);
await page.screenshot({ path: `${OUT}/23_local_forge_done.png` });
s = await stats(); console.log('fake stats', JSON.stringify(s));
ok(/铸造完成/.test(t1), `在线生成 + 自动取回：${t1}`);
ok(s.create === 1 && s.list >= 3 && s.file === 1, `假 Aholo：create ${s.create} 次（之前先 task/list），模型下载 ${s.file} 次`);
const it = await page.evaluate(() => { const its = window.__dlc1.smithy.items(); return { n: its.length, last: its.find(i => i.taskId === '9100001') ?? null, pending: window.__dlc1.smithy.pending() }; });
console.log('items', JSON.stringify(it));
ok(it.n === n0 + 1 && it.last && it.last.size < 2 * 1048576 && !it.pending, `进「我的铸造品」（${it.last?.name}，${(it.last?.size / 1048576).toFixed(2)}MB），没有残留待取任务`);
await page.waitForTimeout(3000);
await page.evaluate(() => window.__dlc1.smithy.open()); await page.waitForTimeout(1500);
ok(await page.evaluate(() => !!document.querySelector('#d1-forge .card.on[data-k="forge_9100001"]')), '「我的铸造品」里标为已换上');
await rect('#fg-mine');
await page.screenshot({ path: `${OUT}/24_local_forge_in_mine.png` });
ok(real.length === 0, `浏览器没有直连 api.aholo3d.cn（${real.length}）`);
ok(!out.includes('fake-good-key'), '服务窗口输出里没有 Key 原文');
ok(errors.length === 0, `页面错误 ${errors.length}${errors.length ? '：' + errors.slice(0, 3).join(' | ') : ''}`);
console.log('--- 服务窗口输出 ---\n' + out.split('\n').slice(-14).join('\n'));
await b.close(); srv.kill(); fake.kill();
console.log(fail ? `FAILED ${fail}` : 'ALL PASS'); process.exit(fail ? 1 : 0);
